type I18nContextType = {
  t: (key: string) => string
  lang: Lang
  setLang: (lang: Lang) => void
}

const I18nContext = createContext<I18nContextType>({
  t: (key) => key,
  lang: "es",
  setLang: () => {},
})

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("es")
  useEffect(() => {
    const stored = localStorage.getItem("dashboard-lang") as Lang | null
    if (stored === "es" || stored === "en" || stored === "zh") {
      setLangState(stored)
    } else {
      const browserLang = navigator.language.toLowerCase()
      setLangState(browserLang.startsWith("es") ? "es" : browserLang.startsWith("zh") ? "zh" : "en")
    }
  }, [])

  const setLang = (next: Lang) => {
    setLangState(next)
    localStorage.setItem("dashboard-lang", next)
  }

  const t = (key: string) => translations[lang][key] || key

  return <I18nContext.Provider value={{ t, lang, setLang }}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}
